/**
 * Local start: Auth emulator + Vite.
 * - Reuses Auth if :9099 (or candidate) already healthy
 * - Else picks a free port, writes firebase.runtime.json + .env.local
 * - Vite keeps running if the emulator exits (no -k)
 */
import { spawn } from "node:child_process";
import fs from "node:fs";
import http from "node:http";
import net from "node:net";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CANDIDATES = [9099, 9100, 9101, 9102, 9103];

function probeListen(port) {
  return new Promise((resolve) => {
    const server = net.createServer();
    server.once("error", () => resolve(false));
    server.once("listening", () => {
      server.close(() => resolve(true));
    });
    server.listen(port, "127.0.0.1");
  });
}

function probeAuth(port) {
  return new Promise((resolve) => {
    const req = http.get(
      { host: "127.0.0.1", port, path: "/", timeout: 400 },
      (res) => {
        res.resume();
        resolve(res.statusCode !== undefined);
      },
    );
    req.on("error", () => resolve(false));
    req.on("timeout", () => {
      req.destroy();
      resolve(false);
    });
  });
}

async function pickAuthPort() {
  for (const port of CANDIDATES) {
    if (await probeAuth(port)) {
      return { port, reuse: true };
    }
  }
  for (const port of CANDIDATES) {
    if (await probeListen(port)) {
      return { port, reuse: false };
    }
  }
  throw new Error(
    `No free Auth emulator port in ${CANDIDATES.join(", ")}. Free one and retry.`,
  );
}

function writeRuntimeConfig(port) {
  const base = JSON.parse(
    fs.readFileSync(path.join(root, "firebase.json"), "utf8"),
  );
  base.emulators = base.emulators || {};
  base.emulators.auth = {
    ...(base.emulators.auth || {}),
    host: "127.0.0.1",
    port,
  };
  const runtimePath = path.join(root, "firebase.runtime.json");
  fs.writeFileSync(runtimePath, `${JSON.stringify(base, null, 2)}\n`);

  const envLocal = path.join(root, ".env.local");
  const authUrl = `http://127.0.0.1:${port}`;
  const lines = [
    `# Generated by scripts/dev-start.mjs — do not commit`,
    `VITE_FIREBASE_AUTH_EMULATOR_URL=${authUrl}`,
    `VITE_USE_EMULATORS=true`,
    "",
  ];
  fs.writeFileSync(envLocal, lines.join("\n"));
  return { runtimePath, authUrl };
}

function run(commandLine, name) {
  const child = spawn(commandLine, {
    cwd: root,
    stdio: "inherit",
    shell: true,
    env: process.env,
  });
  child.on("exit", (code, signal) => {
    const why = signal ? `signal ${signal}` : `code ${code ?? 0}`;
    console.log(`\n[${name}] exited (${why})`);
    if (name === "web") {
      process.exit(code ?? 0);
    } else {
      console.warn(
        `[emu] Auth emulator stopped — Vite keeps running; Try demo uses offline local session if needed.`,
      );
    }
  });
  return child;
}

const { port, reuse } = await pickAuthPort();
const { runtimePath, authUrl } = writeRuntimeConfig(port);

console.log(
  reuse
    ? `[start] Reusing Auth emulator at ${authUrl}`
    : `[start] Starting Auth emulator at ${authUrl}`,
);
console.log(`[start] Vite will keep running even if the emulator fails.`);

const kids = [];
if (!reuse) {
  kids.push(
    run(
      `npx firebase emulators:start --only auth --project work-planner-demo --config ${path.basename(runtimePath)}`,
      "emu",
    ),
  );
}
kids.push(run("npx vite", "web"));

function shutdown() {
  for (const kid of kids) {
    if (!kid.killed) kid.kill("SIGTERM");
  }
}
process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);
